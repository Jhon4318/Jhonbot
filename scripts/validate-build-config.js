const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const pkg = require('../package.json')
const build = pkg.build || {}
const mainSource = fs.readFileSync(require.resolve('../src/main.js'), 'utf8')
const updatePackager = fs.readFileSync(path.join(__dirname, 'create-manual-update-package.ps1'), 'utf8')
const updateApplier = fs.readFileSync(path.join(__dirname, 'Apply-Update.ps1'), 'utf8')
const winTargets = Array.isArray(build.win?.target) ? build.win.target : [build.win?.target]

assert.equal(pkg.main, 'src/main.js', 'Electron entry point must remain src/main.js')
assert.ok(pkg.devDependencies?.electron, 'Electron must be available for development and packaging')
assert.ok(pkg.devDependencies?.['electron-builder'], 'electron-builder must be installed')
assert.equal(pkg.dependencies?.['electron-updater'], undefined, 'The app must not require an in-app updater')
assert.equal(build.publish, undefined, 'No public update provider or public source repository should be configured')
assert.equal(build.appId, 'com.jhonbot.bedrockbotconsole', 'appId must remain stable across upgrades')
assert.ok(mainSource.includes('app.setName(PACKAGE.name)'), 'Electron userData folder name must remain stable across upgrades')
assert.ok(mainSource.includes('appVersion: APP_VERSION'), 'Reported app version must follow package.json')
assert.match(mainSource, /signallingConnectTimeout:\s*30000[\s\S]{0,100}inactivityTimeoutMs:\s*15000/, 'Friend-world NetherNet deadlines must remain explicitly configured')
assert.match(mainSource, /connectTimeout:\s*60000/, 'Friend-world connection watchdog must leave room for its 30s + 15s transport deadlines')
assert.equal(build.asar, true, 'Application files should be packaged in app.asar')
assert.ok(winTargets.some(target => target?.target === 'nsis' && target.arch?.includes('x64')), 'Windows x64 NSIS target is required')
assert.equal(build.nsis?.oneClick, true, 'Installer should use one-click setup')
assert.equal(build.nsis?.perMachine, false, 'Installer should install per user')
assert.equal(build.nsis?.deleteAppDataOnUninstall, false, 'Uninstall must preserve user data')
assert.equal(build.nsis?.language, '1041', 'Installer language must be Japanese (LCID 1041)')
assert.ok(build.files?.includes('src/**/*'), 'Application source must be packaged')
assert.ok(build.files?.includes('package.json'), 'Package metadata must be packaged')
assert.ok(build.files?.includes('scripts/**/*'), 'Application scripts must be packaged')
assert.ok(updatePackager.includes('resources/app.asar'), 'Manual update package must include the application ASAR')
assert.ok(updatePackager.includes('minimumSupportedVersion'), 'Manual update package must declare its minimum supported version')
assert.ok(updateApplier.includes('app.asar'), 'Manual update applier must replace app.asar')
assert.ok(updateApplier.includes('app.asar.backup'), 'Manual update applier must preserve a rollback copy')
assert.ok(updateApplier.includes('Get-FileHash'), 'Manual update applier must verify the downloaded application payload')
assert.ok(updateApplier.includes('electron=([0-9]+'), 'Manual update applier must verify the installed Electron runtime version')
assert.ok(updateApplier.includes('Get-ShortestSameVolumeDirectory'), 'Update work directory must be short and on the installation volume')
assert.ok(updateApplier.includes('Move-Item -LiteralPath $targetUnpacked -Destination $backupUnpacked'), 'Old unpacked files must be moved into backup instead of copied through long paths')
assert.ok(updateApplier.includes('Move-Item -LiteralPath $sourceUnpacked -Destination $targetUnpacked'), 'New unpacked files must be moved into place from the same volume')
assert.ok(!updateApplier.includes('Copy-Item -LiteralPath $sourceUnpacked -Destination $stagedUnpacked'), 'Update applier must not copy deeply nested files into a long installation path')
assert.ok(updateVerifier.includes('Outer ZIP contains unexpectedly long paths'), 'CI must reject long paths in the outer ZIP')
assert.ok(updateVerifier.includes('Expand-Archive'), 'CI must test extraction of the nested ZIP')
assert.ok(fs.existsSync(path.join(__dirname, 'Apply-Update.bat')), 'Manual update package must include a double-click launcher')

console.log(`Windows installer and manual update configuration is valid for Bedrock Bot Console ${pkg.version}.`)
